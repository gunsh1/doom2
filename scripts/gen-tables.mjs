// Generates TypeScript data modules from the GPL linuxdoom-1.10 C sources.
// Usage: node scripts/gen-tables.mjs [path-to-linuxdoom-1.10]
// Default source path is .cache/ref-doom/linuxdoom-1.10 (git clone of id-Software/DOOM).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = process.argv[2] ?? join(root, '.cache', 'ref-doom', 'linuxdoom-1.10');
const read = (f) => readFileSync(join(src, f), 'latin1').replace(/\r/g, '');
const outDir = join(root, 'src', 'generated');
mkdirSync(outDir, { recursive: true });

const HEADER = '// AUTO-GENERATED by scripts/gen-tables.mjs from linuxdoom-1.10 (GPL-2.0). Do not edit.\n';

function stripComments(s) {
  return s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '');
}

// Extract the brace-delimited initializer following `marker`.
function initializer(text, marker) {
  const i = text.indexOf(marker);
  if (i < 0) throw new Error(`marker not found: ${marker}`);
  const start = text.indexOf('{', i);
  let depth = 0;
  for (let j = start; j < text.length; j++) {
    if (text[j] === '{') depth++;
    else if (text[j] === '}') {
      depth--;
      if (depth === 0) return text.slice(start + 1, j);
    }
  }
  throw new Error('unbalanced braces');
}

function numbers(body) {
  return stripComments(body).split(',').map((s) => s.trim()).filter(Boolean).map((s) => Number(s));
}

function enumNames(text, terminator) {
  const end = text.indexOf(terminator);
  const start = text.lastIndexOf('typedef enum', end);
  const body = stripComments(text.slice(text.indexOf('{', start) + 1, text.lastIndexOf('}', end)));
  return body.split(',').map((s) => s.trim()).filter(Boolean).map((s) => s.split('=')[0].trim());
}

// ---- tables.c / m_random.c / v_video.c ----
const tables = stripComments(read('tables.c'));
const finetangent = numbers(initializer(tables, 'finetangent[4096]'));
const finesine = numbers(initializer(tables, 'finesine[10240]'));
const tantoangle = numbers(initializer(tables, 'tantoangle[2049]'));
const rndtable = numbers(initializer(read('m_random.c'), 'rndtable[256]'));
const gammaBody = initializer(read('v_video.c'), 'gammatable[5][256]');
const gamma = numbers(gammaBody.replace(/[{}]/g, ','));
if (finetangent.length !== 4096 || finesine.length !== 10240 || tantoangle.length !== 2049 || rndtable.length !== 256 || gamma.length !== 1280)
  throw new Error('table length mismatch');

writeFileSync(join(outDir, 'tables_data.ts'), HEADER +
  `export const finetangentData = new Int32Array([${finetangent.join(',')}]);\n` +
  `export const finesineData = new Int32Array([${finesine.join(',')}]);\n` +
  `export const tantoangleData = new Uint32Array([${tantoangle.join(',')}]);\n` +
  `export const rndtable = new Uint8Array([${rndtable.join(',')}]);\n` +
  `export const gammatableData = new Uint8Array([${gamma.join(',')}]);\n`);

// ---- info.h / info.c ----
const infoH = read('info.h');
const infoC = read('info.c');
const sprNames = enumNames(infoH, '} spritenum_t');
const stateNames = enumNames(infoH, '} statenum_t');
const mobjNames = enumNames(infoH, '} mobjtype_t');
const soundsH = read('sounds.h');
const sfxNames = enumNames(soundsH, '} sfxenum_t');
const musNames = enumNames(soundsH, '} musicenum_t');

const ids = {};
const addEnum = (names) => names.forEach((n, i) => { ids[n] = i; });
[sprNames, stateNames, mobjNames, sfxNames, musNames].forEach(addEnum);
ids.FRACUNIT = 65536;
for (const m of read('p_mobj.h').matchAll(/(MF_\w+)\s*=\s*(0x[0-9a-fA-F]+|\d+)/g)) ids[m[1]] = Number(m[2]);
ids.NULL = 0;

function evalExpr(expr) {
  const js = expr.trim().replace(/[A-Za-z_]\w*/g, (w) => {
    if (!(w in ids)) throw new Error(`unknown identifier ${w} in ${expr}`);
    return String(ids[w]);
  });
  // eslint-disable-next-line no-new-func
  return Function(`return (${js})|0`)();
}

const actions = new Set();
const statesBody = stripComments(initializer(infoC, 'states[NUMSTATES]'));
const states = [];
for (const m of statesBody.matchAll(/\{\s*(\w+)\s*,\s*([^,]+),\s*([^,]+),\s*\{([^}]*)\}\s*,\s*(\w+)\s*,\s*([^,]+),\s*([^}]+)\}/g)) {
  const action = m[4].trim();
  const act = action === 'NULL' || action === '' ? null : action;
  if (act) actions.add(act);
  states.push([ids[m[1]], evalExpr(m[2]), evalExpr(m[3]), act, ids[m[5]], evalExpr(m[6]), evalExpr(m[7])]);
}
if (states.length !== stateNames.length - 1) throw new Error(`states: ${states.length} != ${stateNames.length - 1}`);

const MOBJ_FIELDS = ['doomednum', 'spawnstate', 'spawnhealth', 'seestate', 'seesound', 'reactiontime', 'attacksound',
  'painstate', 'painchance', 'painsound', 'meleestate', 'missilestate', 'deathstate', 'xdeathstate', 'deathsound',
  'speed', 'radius', 'height', 'mass', 'damage', 'activesound', 'flags', 'raisestate'];
const mobjBody = stripComments(initializer(infoC, 'mobjinfo[NUMMOBJTYPES]'));
const mobjinfo = [];
let depth = 0, cur = '';
for (const ch of mobjBody) {
  if (ch === '{') { depth++; if (depth === 1) { cur = ''; continue; } }
  if (ch === '}') { depth--; if (depth === 0) { mobjinfo.push(cur.split(',').map(evalExpr)); continue; } }
  if (depth >= 1) cur += ch;
}
if (mobjinfo.length !== mobjNames.length - 1) throw new Error('mobjinfo count');

const sprnames = [...initializer(infoC, 'sprnames[NUMSPRITES]').matchAll(/"(\w+)"/g)].map((m) => m[1]);

const enumTs = (names) => names.filter((n) => !n.startsWith('NUM')).map((n, i) => `  ${n}: ${i},`).join('\n');
let info = HEADER;
info += `export const SPR = {\n${enumTs(sprNames)}\n} as const;\n`;
info += `export const S = {\n${enumTs(stateNames)}\n} as const;\n`;
info += `export const MT = {\n${enumTs(mobjNames)}\n} as const;\n`;
info += `export const NUMSPRITES = ${sprNames.length - 1};\nexport const NUMSTATES = ${stateNames.length - 1};\nexport const NUMMOBJTYPES = ${mobjNames.length - 1};\n`;
info += `export const sprnames: readonly string[] = ${JSON.stringify(sprnames)};\n`;
info += `export type ActionName = ${[...actions].map((a) => JSON.stringify(a)).join(' | ')};\n`;
info += `// [sprite, frame, tics, action, nextstate, misc1, misc2]\n`;
info += `export const stateData: ReadonlyArray<readonly [number, number, number, ActionName | null, number, number, number]> = [\n${states.map((s) => '  ' + JSON.stringify(s)).join(',\n')}\n];\n`;
info += `export const MOBJ_FIELDS = ${JSON.stringify(MOBJ_FIELDS)} as const;\n`;
info += `export const mobjinfoData: ReadonlyArray<readonly number[]> = [\n${mobjinfo.map((m) => '  ' + JSON.stringify(m)).join(',\n')}\n];\n`;
writeFileSync(join(outDir, 'info_data.ts'), info);

// ---- sounds.c ----
const sounds = stripComments(read('sounds.c'));
const sfxBody = initializer(sounds, 'S_sfx[]');
const sfx = [];
for (const m of sfxBody.matchAll(/\{\s*"(\w+)"\s*,\s*(\w+)\s*,\s*(-?\d+)\s*,\s*([^,]+),\s*(-?\d+)\s*,\s*(-?\d+)\s*,\s*(-?\d+)\s*\}/g)) {
  const link = m[4].trim();
  const lm = link.match(/S_sfx\[(\w+)\]/);
  sfx.push({ name: m[1], singularity: m[2] === 'true', priority: +m[3], link: lm ? ids[lm[1]] : -1, pitch: +m[5], volume: +m[6] });
}
if (sfx.length !== sfxNames.length - 1) throw new Error(`sfx count ${sfx.length} vs ${sfxNames.length - 1}`);
const musBody = initializer(sounds, 'S_music[]');
const music = [...musBody.matchAll(/\{\s*(?:"(\w+)"[^}]*|0\s*)\}/g)].map((m) => m[1] ?? '');
let snd = HEADER;
snd += `export const SFX = {\n${enumTs(sfxNames)}\n} as const;\n`;
snd += `export const MUS = {\n${enumTs(musNames)}\n} as const;\n`;
snd += `export interface SfxInfo { name: string; singularity: boolean; priority: number; link: number; pitch: number; volume: number }\n`;
snd += `export const sfxData: readonly SfxInfo[] = ${JSON.stringify(sfx)};\n`;
snd += `export const musicNames: readonly string[] = ${JSON.stringify(music)};\n`;
writeFileSync(join(outDir, 'sounds_data.ts'), snd);

// ---- d_englsh.h ----
const englsh = read('d_englsh.h').replace(/\/\/[^\n]*/g, '').replace(/\\\n/g, ' ');
const strs = {};
for (const line of englsh.split('\n')) {
  const m = line.match(/^#define\s+(\w+)\s+(.*)$/);
  if (!m) continue;
  const parts = [...m[2].matchAll(/"((?:[^"\\]|\\.)*)"|([A-Z_][A-Z0-9_]*)/g)];
  if (!parts.length || !m[2].includes('"')) continue;
  let value = '';
  for (const p of parts) {
    if (p[1] !== undefined) value += JSON.parse(`"${p[1].replace(/\\'/g, "'")}"`);
    else if (p[2] in strs) value += strs[p[2]];
  }
  strs[m[1]] = value;
}
writeFileSync(join(outDir, 'strings_data.ts'), HEADER + `export const STR = ${JSON.stringify(strs, null, 1)} as const;\n`);

console.log(`tables ok; ${Object.keys(strs).length} strings,`);
console.log(`tables ok; ${states.length} states, ${mobjinfo.length} mobj types, ${sfx.length} sfx, ${music.length} music, ${actions.size} actions`);
